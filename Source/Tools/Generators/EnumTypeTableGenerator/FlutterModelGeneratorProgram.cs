            if (isTS == false || isAngular == false)
                return string.Empty;
            if (AdditionalPropertyOverloads.Exists(x => x.cName.Trim().ToLower() == cName.Trim().ToLower() && x.pName.Trim().ToLower() == propName.Trim().ToLower()))
            {
