                    var enumItem = Enum.GetName(val.GetType(), val);                   

                    sb.AppendLine($"  {CodeGenUtils.LowerFirstCharacter(enumItem)}({actualValue.ToString()}){sym}");                    
                }

                sb.AppendLine($"");
                sb.AppendLine($"  const {tx.Name}(this.value);");
                sb.AppendLine($"  final int value;");                

                sb.AppendLine($"}}");
                sb.AppendLine($"");
            }

            CodeGenUtils.CleanAndWriteAndOpenFile(GetFlutterModelDirectory(dir) + "\\app-enums.dart", sb);

        }

